// Bundle typed worker entry points ahead of time. Runtime consumers need no bundler or worker assets.
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const banner = '// Generated by scripts/build-audio-workers.mjs; edit the typed worker entry points instead.\n';
let output = banner;
for (const kind of ['pcm', 'native', 'browser']) {
  const result = await build({ absWorkingDir: root, entryPoints: [`src/audio/${kind}-worker.entry.ts`],
    bundle: true, minify: true, write: false, platform: kind === 'native' ? 'node' : 'browser',
    format: 'iife', external: ['node:worker_threads'], target: 'es2022', logLevel: 'silent' });
  const declaration = `export const ${kind}WorkerSource: string = ${JSON.stringify(result.outputFiles[0].text)};\n`;
  if (kind === 'browser') await writeGenerated('browser-worker-source.ts', banner + declaration);
  else output += declaration;
}
await writeGenerated('worker-sources.ts', output);

async function writeGenerated(name, contents) {
  const file = new URL('../src/audio/' + name, import.meta.url);
  if (contents !== await readFile(file, 'utf8').catch(() => '')) {
    if (process.argv.includes('--check')) throw new Error('Audio worker bundles are stale. Run node scripts/build-audio-workers.mjs.');
    await writeFile(file, contents);
  }
}
