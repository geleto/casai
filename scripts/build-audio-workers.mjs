// Bundle typed worker entry points ahead of time. Runtime consumers need no bundler or worker assets.
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
let output = '// Generated by scripts/build-audio-workers.mjs; edit the typed worker entry points instead.\n';
for (const kind of ['pcm', 'native']) {
  const result = await build({ absWorkingDir: root, entryPoints: [`src/audio/${kind}-worker.entry.ts`],
    bundle: true, minify: true, write: false, platform: kind === 'pcm' ? 'browser' : 'node',
    format: 'iife', external: ['node:worker_threads'], target: 'es2022', logLevel: 'silent' });
  output += `export const ${kind}WorkerSource: string = ${JSON.stringify(result.outputFiles[0].text)};\n`;
}
const file = new URL('../src/audio/worker-sources.ts', import.meta.url);
const previous = await readFile(file, 'utf8').catch(() => '');
if (output !== previous) {
  if (process.argv.includes('--check')) throw new Error('Audio worker bundles are stale. Run node scripts/build-audio-workers.mjs.');
  await writeFile(file, output);
}
